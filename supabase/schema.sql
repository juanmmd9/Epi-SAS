-- ============================== TABLAS ===============================

-- Catalogo de maquinas y equipos (base maestra del sistema)
create table if not exists hojas_vida (
  id uuid primary key default gen_random_uuid(),
  codigo text,
  nombre text not null,
  area text not null,
  frecuencia_pm_meses integer,
  primer_pm date,
  activa boolean not null default true,
  foto_url text,
  datos jsonb not null default '{}',
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

-- Registros de mantenimiento preventivo
create table if not exists preventivo (
  id uuid primary key default gen_random_uuid(),
  hoja_id uuid references hojas_vida (id) on delete set null,
  area text not null,
  fecha date not null,
  descripcion text,
  adjunto_url text,
  datos jsonb not null default '{}',
  creado_en timestamptz not null default now()
);

-- Solicitudes de mantenimiento correctivo
create table if not exists correctivo (
  id uuid primary key default gen_random_uuid(),
  area text not null,
  fecha date not null,
  datos jsonb not null default '{}',
  creado_en timestamptz not null default now()
);

-- Programaciones puntuales del cronograma preventivo
create table if not exists cronograma (
  id uuid primary key default gen_random_uuid(),
  hoja_id uuid references hojas_vida (id) on delete cascade,
  fecha date not null,
  datos jsonb not null default '{}',
  creado_en timestamptz not null default now()
);

-- Dias excluidos del cronograma
create table if not exists cronograma_excepciones (
  id uuid primary key default gen_random_uuid(),
  fecha date not null,
  motivo text,
  creado_en timestamptz not null default now()
);

-- No conformidades (formato GC-RE-009)
create table if not exists no_conformidades (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  pdf_url text,
  datos jsonb not null default '{}',
  creado_en timestamptz not null default now()
);

-- Horas programadas por mes y area (indicadores)
create table if not exists horas_programadas (
  id uuid primary key default gen_random_uuid(),
  periodo text not null, -- formato YYYY-MM
  area text not null,
  horas numeric not null default 0,
  unique (periodo, area)
);

-- Personal de mantenimiento
create table if not exists personal (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  cargo text,
  area text,
  cedula text,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

alter table personal add column if not exists cedula text;

-- Vinculo opcional con personal (ejecutar si la tabla ya existia)
alter table preventivo add column if not exists personal_id uuid references personal (id) on delete set null;
alter table correctivo add column if not exists personal_id uuid references personal (id) on delete set null;

