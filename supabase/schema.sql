-- Matriz de conocimientos y habilidades (Mantenimiento Mecánico)
create table if not exists competencias_matriz (
  id uuid primary key default gen_random_uuid(),
  hoja text not null default 'MECANICO',
  orden integer not null,
  numero integer,
  categoria text not null,
  descripcion text not null,
  meta_d integer not null default 2 check (meta_d >= 0 and meta_d <= 4),
  experto text,
  herramienta text,
  estado_capacitacion text,
  activa boolean not null default true,
  unique (hoja, orden)
);

create table if not exists matriz_conocimiento (
  id uuid primary key default gen_random_uuid(),
  personal_id uuid not null references personal (id) on delete cascade,
  competencia_id uuid not null references competencias_matriz (id) on delete cascade,
  nivel_i integer not null default 1 check (nivel_i >= 0 and nivel_i <= 4),
  nivel_d integer not null default 2 check (nivel_d >= 0 and nivel_d <= 4),
  nivel_h integer not null default 0 check (nivel_h >= 0 and nivel_h <= 4),
  actualizado_en timestamptz not null default now(),
  unique (personal_id, competencia_id)
);

alter table competencias_matriz enable row level security;
alter table matriz_conocimiento enable row level security;

-- GH-RE-030 Permisos y horario laboral
create table if not exists horario_laboral (
  id uuid primary key default gen_random_uuid(),
  anio integer not null,
  dia_semana smallint not null check (dia_semana >= 0 and dia_semana <= 6),
  turno smallint not null default 1 check (turno >= 1 and turno <= 2),
  hora_inicio time not null,
  hora_fin time not null,
  activo boolean not null default true,
  unique (anio, dia_semana, turno)
);

create table if not exists festivos (
  id uuid primary key default gen_random_uuid(),
  anio integer not null,
  fecha date not null,
  descripcion text,
  unique (anio, fecha)
);

create table if not exists permisos_personal (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  personal_id uuid not null references personal (id) on delete cascade,
  estado text not null default 'solicitado'
    check (estado in ('borrador', 'solicitado', 'autorizado', 'en_permiso', 'cerrado')),
  pdf_url text,
  datos jsonb not null default '{}',
  creado_en timestamptz not null default now()
);

alter table horario_laboral enable row level security;
alter table festivos enable row level security;
alter table permisos_personal enable row level security;

